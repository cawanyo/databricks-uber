CREATE OR REFRESH STREAMING TABLE silver_obt
AS
WITH stg_rides_typed AS (
    SELECT
        dev.silver.stg_rides.base_fare,
        to_timestamp(dev.silver.stg_rides.booking_timestamp) AS booking_timestamp,
        dev.silver.stg_rides.cancellation_reason_id,
        dev.silver.stg_rides.confirmation_number,
        dev.silver.stg_rides.distance_fare,
        dev.silver.stg_rides.distance_miles,
        dev.silver.stg_rides.driver_id,
        dev.silver.stg_rides.driver_license,
        dev.silver.stg_rides.driver_name,
        dev.silver.stg_rides.driver_phone,
        dev.silver.stg_rides.driver_rating,
        dev.silver.stg_rides.dropoff_address,
        dev.silver.stg_rides.dropoff_city_id,
        dev.silver.stg_rides.dropoff_latitude,
        dev.silver.stg_rides.dropoff_location_id,
        dev.silver.stg_rides.dropoff_longitude,
        dev.silver.stg_rides.dropoff_timestamp,
        dev.silver.stg_rides.duration_minutes,
        dev.silver.stg_rides.license_plate,
        dev.silver.stg_rides.passenger_email,
        dev.silver.stg_rides.passenger_id,
        dev.silver.stg_rides.passenger_name,
        dev.silver.stg_rides.passenger_phone,
        dev.silver.stg_rides.payment_method_id,
        dev.silver.stg_rides.pickup_address,
        dev.silver.stg_rides.pickup_city_id,
        dev.silver.stg_rides.pickup_latitude,
        dev.silver.stg_rides.pickup_location_id,
        dev.silver.stg_rides.pickup_longitude,
        dev.silver.stg_rides.pickup_timestamp,
        dev.silver.stg_rides.rating,
        dev.silver.stg_rides.ride_id,
        dev.silver.stg_rides.ride_status_id,
        dev.silver.stg_rides.subtotal,
        dev.silver.stg_rides.surge_multiplier,
        dev.silver.stg_rides.time_fare,
        dev.silver.stg_rides.tip_amount,
        dev.silver.stg_rides.total_fare,
        dev.silver.stg_rides.vehicle_color,
        dev.silver.stg_rides.vehicle_id,
        dev.silver.stg_rides.vehicle_make_id,
        dev.silver.stg_rides.vehicle_model,
        dev.silver.stg_rides.vehicle_type_id
    FROM STREAM (dev.silver.stg_rides)
)
SELECT 
    stg_rides_typed.base_fare,
    stg_rides_typed.booking_timestamp,
    stg_rides_typed.cancellation_reason_id,
    stg_rides_typed.confirmation_number,
    stg_rides_typed.distance_fare,
    stg_rides_typed.distance_miles,
    stg_rides_typed.driver_id,
    stg_rides_typed.driver_license,
    stg_rides_typed.driver_name,
    stg_rides_typed.driver_phone,
    stg_rides_typed.driver_rating,
    stg_rides_typed.dropoff_address,
    stg_rides_typed.dropoff_city_id,
    stg_rides_typed.dropoff_latitude,
    stg_rides_typed.dropoff_location_id,
    stg_rides_typed.dropoff_longitude,
    stg_rides_typed.dropoff_timestamp,
    stg_rides_typed.duration_minutes,
    stg_rides_typed.license_plate,
    stg_rides_typed.passenger_email,
    stg_rides_typed.passenger_id,
    stg_rides_typed.passenger_name,
    stg_rides_typed.passenger_phone,
    stg_rides_typed.payment_method_id,
    stg_rides_typed.pickup_address,
    stg_rides_typed.pickup_city_id,
    stg_rides_typed.pickup_latitude,
    stg_rides_typed.pickup_location_id,
    stg_rides_typed.pickup_longitude,
    stg_rides_typed.pickup_timestamp,
    stg_rides_typed.rating,
    stg_rides_typed.ride_id,
    stg_rides_typed.ride_status_id,
    stg_rides_typed.subtotal,
    stg_rides_typed.surge_multiplier,
    stg_rides_typed.time_fare,
    stg_rides_typed.tip_amount,
    stg_rides_typed.total_fare,
    stg_rides_typed.vehicle_color,
    stg_rides_typed.vehicle_id,
    stg_rides_typed.vehicle_make_id,
    stg_rides_typed.vehicle_model,
    stg_rides_typed.vehicle_type_id,
    dev.bronze.map_vehicle_types.vehicle_type,
    dev.bronze.map_vehicle_types.base_rate,
    dev.bronze.map_vehicle_types.per_mile,
    dev.bronze.map_vehicle_types.per_minute,
    dev.bronze.map_vehicle_makes.vehicle_make,
    dev.bronze.map_cities.city,
    dev.bronze.map_cities.region,
    dev.bronze.map_cities.state,
    dev.bronze.map_cancellation_reasons.cancellation_reason
FROM 
    stg_rides_typed
    WATERMARK booking_timestamp DELAY OF INTERVAL 3 MINUTES
    LEFT JOIN dev.bronze.map_vehicle_types ON stg_rides_typed.vehicle_type_id = dev.bronze.map_vehicle_types.vehicle_type_id
    LEFT JOIN dev.bronze.map_vehicle_makes ON stg_rides_typed.vehicle_make_id = dev.bronze.map_vehicle_makes.vehicle_make_id
    LEFT JOIN dev.bronze.map_cities ON stg_rides_typed.pickup_city_id = dev.bronze.map_cities.city_id
    LEFT JOIN dev.bronze.map_cancellation_reasons ON stg_rides_typed.cancellation_reason_id = dev.bronze.map_cancellation_reasons.cancellation_reason_id
